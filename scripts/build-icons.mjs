// artwork comes from Lucide. Run after changing the maps below:
//   node scripts/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'node_modules', 'lucide-static', 'icons');

// lesson icon name -> lucide icon
const SCENE = {
  // people & devices
  user: 'user-round', users: 'users-round', incognito: 'venetian-mask', browser: 'app-window', phone: 'smartphone', laptop: 'laptop',
  // infrastructure
  server: 'server', database: 'database', table: 'table-2', cloud: 'cloud', function: 'square-function', api: 'webhook', globe: 'globe',
  queue: 'rows-3', bolt: 'zap', box: 'package', layers: 'layers', rocket: 'rocket',
  // security
  key: 'key-round', lock: 'lock', unlock: 'lock-open', shield: 'shield', cookie: 'cookie', token: 'ticket', 'id-card': 'id-card', eye: 'eye', ban: 'ban',
  // files & data
  file: 'file-text', folder: 'folder', list: 'list', search: 'search', chart: 'chart-line',
  // dev tools
  code: 'code-xml', terminal: 'square-terminal', git: 'git-branch', bug: 'bug', log: 'scroll-text', gear: 'settings', flask: 'flask-conical', pencil: 'pencil',
  // AI
  sparkle: 'sparkles', brain: 'brain', chat: 'message-square', robot: 'bot', vector: 'move-3d',
  // status & time
  clock: 'clock', check: 'check', x: 'x', alert: 'triangle-alert', bell: 'bell', refresh: 'refresh-cw', link: 'link', upload: 'upload', download: 'download', trash: 'trash-2',
  // business
  mail: 'mail', calendar: 'calendar', money: 'banknote', cart: 'shopping-cart', handshake: 'handshake', 'graduation-cap': 'graduation-cap',
};
